"""Benchmark AEGIS on the red-team scenarios.

    python scripts/benchmark.py            # prints a report, writes docs/BENCHMARK.md and docs/benchmark.json

Measures, over the scripted scenarios in aegis/agents/scenarios.py (each step is labelled harmful or legitimate):
  * prevention   - harmful actions that were masked, held for a human, or blocked
  * detection    - harmful actions that raised any signal (including flag-and-allow)
  * friction     - legitimate actions that were held or blocked
  * latency      - time for the full decision pipeline, replayed many times
  * depth        - how many harmful actions are still stopped when any single detector is switched off
"""
from __future__ import annotations

import asyncio
import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from aegis.agents.scenarios import SCENARIOS, run_scenario  # noqa: E402
from aegis.detectors import DETECTOR_LABELS  # noqa: E402
from aegis.engine import Gateway  # noqa: E402
from aegis.models import Decision  # noqa: E402
from aegis.policy import Policy  # noqa: E402

POLICY = Policy.load(ROOT / "policies" / "default.yaml")
RANK = {d.value: d.rank for d in Decision}
REPEATS = 60


def run_all(disabled: str | None = None) -> list[dict]:
    rows = []
    for sc in SCENARIOS:
        gw = Gateway(POLICY)
        if disabled:
            gw.detectors = [d for d in gw.detectors if d.__name__ != disabled]
        result = asyncio.run(run_scenario(gw, sc, delay=0, auto_review=True))
        for step, r in zip(sc.steps, result["steps"]):
            rows.append({"scenario": sc.id, "tool": r["tool"], "attack": step.attack, "expected": step.expect,
                         "decision": r["decision"], "latency_ms": r["latency_ms"]})
    return rows


def pct(values: list[float], p: float) -> float:
    s = sorted(values)
    return s[min(len(s) - 1, int(p * len(s)))]


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    rows = run_all()
    harmful = [r for r in rows if r["attack"]]
    legit = [r for r in rows if not r["attack"]]
    prevented = [r for r in harmful if RANK[r["decision"]] >= RANK["redact"]]
    detected = [r for r in harmful if r["decision"] != "allow"]
    held_or_blocked = [r for r in legit if RANK[r["decision"]] >= RANK["escalate"]]
    by_policy = [r for r in held_or_blocked if r["expected"] == "escalate"]  # deliberate human-approval steps
    wrongly_stopped = [r for r in held_or_blocked if r["expected"] != "escalate"]
    matches = sum(r["decision"] == r["expected"] for r in rows)

    t0 = time.perf_counter()
    latencies: list[float] = []
    for _ in range(REPEATS):
        latencies += [r["latency_ms"] for r in run_all()]
    wall = time.perf_counter() - t0

    depth = {}
    for det in [d for d in DETECTOR_LABELS if d not in ("baseline", "injection")]:
        fn_name = {"policy": "custom_rules", "data-leak": "data_leak"}.get(det, det)
        ablated = [r for r in run_all(disabled=fn_name) if r["attack"]]
        depth[det] = sum(RANK[r["decision"]] >= RANK["redact"] for r in ablated)

    report = {
        "scenarios": len(SCENARIOS),
        "actions": len(rows),
        "expected_decision_matches": matches,
        "harmful": len(harmful),
        "harmful_prevented": len(prevented),
        "harmful_detected": len(detected),
        "legitimate": len(legit),
        "legitimate_auto": len(legit) - len(held_or_blocked),
        "legitimate_human_approval_by_policy": len(by_policy),
        "legitimate_wrongly_stopped": len(wrongly_stopped),
        "decisions_timed": len(latencies),
        "latency_ms": {"p50": round(statistics.median(latencies), 3), "p95": round(pct(latencies, 0.95), 3),
                       "p99": round(pct(latencies, 0.99), 3), "mean": round(statistics.mean(latencies), 3)},
        "decisions_per_second_single_core": round(len(latencies) / sum(latencies) * 1000),
        "defence_in_depth": {DETECTOR_LABELS[k]: f"{v}/{len(harmful)}" for k, v in depth.items()},
        "per_action": rows,
        "wall_seconds": round(wall, 2),
    }

    lines = [
        "# AEGIS benchmark", "",
        f"Generated by `python scripts/benchmark.py` over the {report['scenarios']} red-team scenarios "
        f"({report['actions']} agent actions, each labelled harmful or legitimate).", "",
        "| Metric | Result |", "|---|---|",
        f"| Decisions matching the expected outcome | {matches}/{len(rows)} |",
        f"| Harmful actions prevented (masked, held or blocked) | {len(prevented)}/{len(harmful)} |",
        f"| Harmful actions detected (incl. flag-and-alert) | {len(detected)}/{len(harmful)} |",
        f"| Legitimate actions that ran automatically | {report['legitimate_auto']}/{len(legit)} |",
        f"| Legitimate actions sent to a human by policy (high-value refund) | {len(by_policy)} |",
        f"| Legitimate actions wrongly held or blocked | {len(wrongly_stopped)} |",
        f"| Decision latency p50 / p95 / p99 | {report['latency_ms']['p50']} / {report['latency_ms']['p95']} / "
        f"{report['latency_ms']['p99']} ms ({len(latencies):,} decisions) |",
        f"| Throughput (one CPU core, full pipeline) | ~{report['decisions_per_second_single_core']:,} decisions/s |",
        "", "## Defence in depth", "",
        "Harmful actions still prevented when one detector is switched off:", "",
        "| Detector switched off | Still prevented |", "|---|---|",
        *[f"| {name} | {v} |" for name, v in report["defence_in_depth"].items()],
        "", "## Per-action results", "", "| Scenario | Tool | Harmful | Expected | AEGIS |", "|---|---|---|---|---|",
        *[f"| {r['scenario']} | `{r['tool']}` | {'yes' if r['attack'] else 'no'} | {r['expected']} | {r['decision']} |"
          for r in rows],
        "", "Note: the scenarios are written by the AEGIS team, so these numbers show the system works as designed; "
            "they are not an independent evaluation.",
    ]
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "BENCHMARK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (docs / "benchmark.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print("\n".join(lines[:16 + len(depth) + 4]))


if __name__ == "__main__":
    main()
